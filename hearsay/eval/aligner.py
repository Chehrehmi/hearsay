from typing import List, Dict, Any


class RAGTruthAligner:
    """Aligns character-offset RAGTruth annotations with discrete sentence/claim boundaries."""

    @staticmethod
    def align_sentence_labels(
        response_text: str,
        labels: List[Dict[str, Any]],
        sentences: List[str]
    ) -> List[Dict[str, Any]]:
        """
        Maps RAGTruth character offset labels (start, end) to discrete sentence predictions.
        
        Args:
            response_text: Full response string generated by LLM.
            labels: List of hallucination label dicts from RAGTruth (each with 'start', 'end', 'label_type').
            sentences: List of sentences/claims decomposed from response_text.
            
        Returns:
            List of sentence target dicts containing sentence text, offsets, binary is_hallucination target, and label_type.
        """
        sentence_targets = []
        current_offset = 0

        for sent in sentences:
            # Find start position of sentence in response_text starting after current_offset
            sent_start = response_text.find(sent, current_offset)
            if sent_start == -1:
                # Fallback to current_offset if exact substring search fails
                sent_start = current_offset

            sent_end = sent_start + len(sent)
            current_offset = sent_end

            has_hallucination = False
            matched_label_type = "Supported"
            matched_labels = []

            # Check overlap between sentence interval [sent_start, sent_end) and label interval [l_start, l_end)
            for lbl in labels:
                l_start = lbl["start"]
                l_end = lbl["end"]

                # Half-open interval overlap mathematical condition
                if max(sent_start, l_start) < min(sent_end, l_end):
                    has_hallucination = True
                    matched_label_type = lbl.get("label_type", "Hallucination")
                    matched_labels.append(lbl)

            sentence_targets.append({
                "sentence": sent,
                "start": sent_start,
                "end": sent_end,
                "is_hallucination": 1 if has_hallucination else 0,
                "label_type": matched_label_type,
                "overlapping_labels": matched_labels,
            })

        return sentence_targets
